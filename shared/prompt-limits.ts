/**
 * Единые потолки длины пользовательских промптов и инструкций.
 *
 * До появления этого файла каждый экран нёс своё число (4 000 у библиотеки промптов,
 * 20 000 у инструкции ассистента, 2 000/4 000 у полей нод, 8 000 у RAG базы знаний,
 * 50 000 у навыков). Разброс был не решением, а наследством: одинаковые по смыслу поля
 * получали разный потолок, а самый низкий из них (4 000) молча резал промпт владельца.
 *
 * Правило разделения:
 * - PROMPT_TEXT_MAX — главный текст промпта, который целиком уходит в модель как задача:
 *   тело промпта библиотеки, инструкция ассистента, шаблон промпта действия, systemPrompt
 *   узла сценария и провайдера, промпты переписывания и ранжирования, инструкция навыка.
 * - PROMPT_FIELD_INSTRUCTION_MAX — короткая инструкция ОДНОГО поля внутри узла сценария:
 *   она дополняет общий промпт узла, а не заменяет его, поэтому потолок ниже.
 *
 * Значения — константы, а не настройка: это защита от опечатки и от вставки всего документа
 * в поле промпта, а не тарифицируемый ресурс. Реальную границу задаёт контекстное окно модели,
 * и оно на порядок больше: 50 000 символов ≈ 12–15 тыс. токенов против 262 тыс. окна прод-модели.
 */

/** Потолок «длинного» промпта: главный текст задачи для модели. */
export const PROMPT_TEXT_MAX = 50_000;

/** Потолок «короткой» инструкции поля внутри узла сценария. */
export const PROMPT_FIELD_INSTRUCTION_MAX = 20_000;

/**
 * Текст ошибки о превышении: называет и потолок, и фактическую длину. Без второго числа
 * пользователь не понимает, сколько лишнего убирать, и правит текст вслепую.
 */
export function formatPromptLengthError(label: string, limit: number, actual: number): string {
  return `${label} длиннее ${limit} символов (сейчас ${actual})`;
}

/** Форма issue, которой достаточно для сообщения; сузана до нужного, чтобы не тянуть типы zod. */
type PromptLengthIssue = {
  readonly maximum?: unknown;
  readonly input?: unknown;
};

/**
 * Параметры для `z.string().max(...)`: подставляют в сообщение фактическую длину значения.
 * Отдаётся объектом, а не строкой, потому что строковая форма zod знает только потолок.
 */
export function promptLengthErrorParams(label: string, limit: number) {
  return {
    error: (issue: PromptLengthIssue) => {
      const maximum = typeof issue.maximum === "number" ? issue.maximum : limit;
      const actual = typeof issue.input === "string" ? issue.input.length : maximum;
      return formatPromptLengthError(label, maximum, actual);
    },
  };
}
